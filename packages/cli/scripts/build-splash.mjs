// renders ducks.png into src/product/splash-art.ts; run `npm run build:splash` when the image changes
import { readFileSync, writeFileSync } from 'fs'
import { inflateSync } from 'zlib'
import b4a from 'b4a'

// widest first: splash() takes the widest cut that fits, so a short window still gets a duck
const SIZES = [64, 48, 32, 24]
// the backdrop and faintest traces drop out so the ducks float on the terminal's own background
const BACKDROP = 90

const source = new URL('../docs/assets/ducks.png', import.meta.url)
const target = new URL('../src/product/splash-art.ts', import.meta.url)

const image = decodePng(readFileSync(source))
const backdrop = { r: image.pixels[0], g: image.pixels[1], b: image.pixels[2] }
// the full canvas, margin included: the illustration is composed square
const arts = SIZES.map((cols) => ({ cols, rows: toRows(resample(image, cols, cols), cols, cols) }))

writeFileSync(
  target,
  `// Generated by scripts/build-splash.mjs from ducks.png — do not edit.
export const SIZES = [
${arts
  .map(
    ({ cols, rows }) => `  {
    width: ${cols},
    rows: [
${rows.map((row) => `      ${JSON.stringify(row)}`).join(',\n')}
    ]
  }`
  )
  .join(',\n')}
]
`
)
console.log(
  `[tui] splash -> src/product/splash-art.ts (${arts
    .map(({ cols, rows }) => `${cols}x${rows.length}`)
    .join(', ')})`
)

function decodePng(buf) {
  const width = b4a.readUInt32BE(buf, 16)
  const height = b4a.readUInt32BE(buf, 20)
  if (buf[24] !== 8 || buf[25] !== 6 || buf[28] !== 0) {
    throw new Error(
      `ducks.png must be 8-bit RGBA, non-interlaced (got ${buf[24]}/${buf[25]}/${buf[28]})`
    )
  }

  const idat = []
  for (let i = 8; i < buf.length;) {
    const len = b4a.readUInt32BE(buf, i)
    if (b4a.toString(buf, 'latin1', i + 4, i + 8) === 'IDAT') {
      idat.push(buf.subarray(i + 8, i + 8 + len))
    }

    i += 12 + len
  }

  const raw = inflateSync(b4a.concat(idat))
  const stride = width * 4
  const pixels = b4a.alloc(height * stride)
  for (let y = 0; y < height; y++) {
    const predict = predictor(raw[y * (stride + 1)])
    const line = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1))
    const out = pixels.subarray(y * stride, (y + 1) * stride)
    const prev = y > 0 ? pixels.subarray((y - 1) * stride, y * stride) : null
    for (let x = 0; x < stride; x++) {
      const a = x >= 4 ? out[x - 4] : 0
      const b = prev ? prev[x] : 0
      const c = prev && x >= 4 ? prev[x - 4] : 0
      out[x] = line[x] + predict(a, b, c)
    }
  }

  return { width, height, pixels }
}

function predictor(filter) {
  if (filter === 0) {
    return () => 0
  }

  if (filter === 1) {
    return (a) => a
  }

  if (filter === 2) {
    return (a, b) => b
  }

  if (filter === 3) {
    return (a, b) => (a + b) >> 1
  }

  return paeth
}

function paeth(a, b, c) {
  const p = a + b - c
  const pa = Math.abs(p - a)
  const pb = Math.abs(p - b)
  const pc = Math.abs(p - c)
  if (pa <= pb && pa <= pc) {
    return a
  }

  return pb <= pc ? b : c
}

function resample({ width, height, pixels }, cols, rows) {
  const out = []
  for (let ty = 0; ty < rows; ty++) {
    for (let tx = 0; tx < cols; tx++) {
      out.push(
        averageCell(
          { width, pixels },
          {
            x0: Math.floor((tx * width) / cols),
            y0: Math.floor((ty * height) / rows),
            x1: Math.floor(((tx + 1) * width) / cols),
            y1: Math.floor(((ty + 1) * height) / rows)
          }
        )
      )
    }
  }

  return out
}

// weight colour by alpha so transparent edges don't drag the average toward black
function averageCell({ width, pixels }, { x0, y0, x1, y1 }) {
  let r = 0
  let g = 0
  let b = 0
  let a = 0
  let n = 0
  for (let y = y0; y < y1; y++) {
    for (let x = x0; x < x1; x++) {
      const i = (y * width + x) * 4
      const weight = pixels[i + 3] / 255
      r += pixels[i] * weight
      g += pixels[i + 1] * weight
      b += pixels[i + 2] * weight
      a += pixels[i + 3]
      n++
    }
  }

  const weight = a / 255 || 1

  return {
    r: Math.round(r / weight),
    g: Math.round(g / weight),
    b: Math.round(b / weight),
    a: Math.round(a / n)
  }
}

function toRows(samples, cols, height) {
  const rows = []
  for (let y = 0; y < height; y += 2) {
    let row = ''
    let fg = null
    let bg = null
    for (let x = 0; x < cols; x++) {
      const top = samples[y * cols + x]
      const bottom = samples[(y + 1) * cols + x]
      const topBlank = blank(top)
      const bottomBlank = blank(bottom)
      if (topBlank && bottomBlank) {
        row += bg === null ? ' ' : '\x1b[49m '
        bg = null
        continue
      }

      // the surviving half is foreground, so a blank half shows the terminal background
      const face = topBlank ? '▄' : '▀'
      const ink = topBlank ? bottom : top
      const fill = topBlank || bottomBlank ? null : bottom
      const inkKey = key(ink)
      const fillKey = fill && key(fill)
      if (inkKey !== fg) {
        row += `\x1b[38;2;${ink.r};${ink.g};${ink.b}m`
        fg = inkKey
      }

      if (fillKey !== bg) {
        row += fill ? `\x1b[48;2;${fill.r};${fill.g};${fill.b}m` : '\x1b[49m'
        bg = fillKey
      }

      row += face
    }

    rows.push(`${row}\x1b[0m`)
  }

  return rows
}

function key({ r, g, b }) {
  return `${r},${g},${b}`
}

function blank(p) {
  return (
    p.a < 128 ||
    Math.abs(p.r - backdrop.r) + Math.abs(p.g - backdrop.g) + Math.abs(p.b - backdrop.b) < BACKDROP
  )
}
