import test from 'brittle'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

test('a worker entry generated by an older SDK asks for the bundle to be made again', async function (t) {
  t.timeout(10_000)

  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'qvac-stale-entry-'))
  const entry = path.join(dir, 'worker.entry.mjs')
  fs.writeFileSync(
    entry,
    'import { initializeWorker } from "@qvac/sdk/worker-lifecycle";\ninitializeWorker();\n'
  )
  process.env['QVAC_WORKER_PATH'] = entry

  const { getRPC, close } = await import('#rpc')

  t.teardown(async () => {
    try {
      await close()
    } catch {}
    delete process.env['QVAC_WORKER_PATH']
    fs.rmSync(dir, { recursive: true, force: true })
  })

  const error = (await getRPC().catch((thrown: unknown) => thrown)) as Error
  t.is((error as { name?: string }).name, 'WORKER_STARTUP_FAILED')
  t.ok(error.message.includes('qvac bundle sdk'))
})
