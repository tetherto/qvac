import { z } from 'zod'

/**
 * Caller session identity. The SDK client stamps every request sent through a
 * session handle with the session's id; a request without one runs as the
 * owner session (the process that started the runtime).
 */
export const sessionIdSchema = z
  .string()
  .min(1)
  .describe(
    'Identifier of the caller session this request belongs to. Omitted for ' +
      'requests made by the runtime owner.'
  )

/**
 * Caller-minted request identity. Surfaces on the handle the SDK returns so the
 * same caller can target the request with `cancel({ requestId })`. The engine
 * keys its registry by `(sessionId, requestId)`, so ids only have to be unique
 * within one session.
 */
export const requestIdSchema = z
  .string()
  .min(1)
  .describe(
    'Stable identifier for this in-flight request, generated by the caller at ' +
      'call time. Surfaces on the returned handle so the caller can target it ' +
      'with `cancel({ requestId })`. Optional: the engine generates one when the ' +
      'field is missing. Scoped to the caller session; another session cannot ' +
      'address it.'
  )

/**
 * Base of every request schema. A request schema is built as
 * `<own fields>.extend(sessionScopedRequestSchema.shape)`, which appends the
 * base fields after the method's own so the wire property order, and with it
 * the generated Kotlin constructor order, stays stable.
 * `test/request-schemas-base-fields.test.ts` fails for a member of
 * `requestSchema` that lacks them.
 */
export const sessionScopedRequestSchema = z.object({
  sessionId: sessionIdSchema.optional()
})

/** Base of every request schema that registers work the caller can cancel. */
export const trackedRequestSchema = sessionScopedRequestSchema.extend({
  requestId: requestIdSchema.optional()
})

export type SessionScopedRequest = z.infer<typeof sessionScopedRequestSchema>
export type TrackedRequest = z.infer<typeof trackedRequestSchema>
