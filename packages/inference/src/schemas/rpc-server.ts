import { z } from 'zod'
import { errorResponseSchema } from './error'

const topicSchema = z.string().trim().min(1).max(256)
const octet = '(?:25[0-5]|2[0-4][0-9]|1[0-9]{2}|[1-9]?[0-9])'
const privateIpv4 = new RegExp(
  `^(?:10\\.${octet}|172\\.(?:1[6-9]|2[0-9]|3[01])|192\\.168)\\.${octet}\\.${octet}$`
)
const lanAddressesSchema = z
  .array(z.string().regex(privateIpv4))
  .min(1)
  .max(8)
  .refine(
    (addresses) => new Set(addresses).size === addresses.length,
    'LAN addresses must be unique'
  )
  .optional()
  .describe(
    'Explicit local private IPv4 addresses. Bypasses automatic adapter-name selection only. Each address must be noninternal with a valid host address and subnet mask. This cannot prove an adapter is physical.'
  )

const requestIdSchema = z
  .string()
  .min(1)
  .optional()
  .describe(
    'Caller-generated identifier for targeted cancellation with cancel({ requestId }). Generated by the engine when omitted.'
  )
export const startRpcServerOptionsSchema = z.object({
  lanAddresses: lanAddressesSchema,
  host: z
    .string()
    .min(1)
    .optional()
    .describe(
      'IPv4 bind address. Defaults to 127.0.0.1. With discoveryTopic and allowNonLoopbackHost: true, omission selects the only eligible private IPv4 Wi-Fi or Ethernet address. Multiple eligible addresses require an explicit host.'
    ),
  port: z
    .number()
    .int()
    .min(1)
    .max(65535)
    .optional()
    .describe('TCP port. Omit to let the native server bind a free port.'),
  device: z
    .union([z.string().min(1), z.array(z.string().min(1)).min(1)])
    .optional()
    .describe('Native server devices, in caller order.'),
  cache: z.boolean().optional().describe('Enable the native RPC tensor cache.'),
  threads: z.number().int().positive().optional().describe('Native server thread count.'),
  expectRdma: z
    .boolean()
    .optional()
    .describe(
      'Require runtime RDMA availability. On Linux, this needs a capable native backend, libibverbs, an RDMA device, and GGML_RPC_NO_RDMA unset. Reject before startup if unavailable.'
    ),
  allowNonLoopbackHost: z
    .boolean()
    .optional()
    .describe(
      'Explicitly allow a non-loopback bind on a trusted private network. This does not authenticate clients.'
    ),
  discoveryTopic: topicSchema
    .optional()
    .describe(
      'Opt in to advertising a ready private IPv4 endpoint under this shared topic. The topic does not authenticate peers.'
    )
})
export const rpcServerInfoSchema = z.object({
  serverId: z.string().min(1),
  url: z.string().min(1),
  rdmaCapable: z
    .boolean()
    .describe(
      'Whether the server will try RDMA. On Linux, this requires a capable native backend, libibverbs, an RDMA device, and GGML_RPC_NO_RDMA unset. Each connection can still fall back to TCP.'
    )
})
export const startRpcServerRequestSchema = startRpcServerOptionsSchema.extend({
  type: z.literal('startRpcServer'),
  requestId: requestIdSchema
})
export const startRpcServerResponseSchema = rpcServerInfoSchema.extend({
  type: z.literal('startRpcServer')
})
export const stopRpcServerOptionsSchema = z.object({ serverId: z.string().min(1) })
export const stopRpcServerRequestSchema = stopRpcServerOptionsSchema.extend({
  type: z.literal('stopRpcServer')
})
export const stopRpcServerResponseSchema = z.object({ type: z.literal('stopRpcServer') })
export const discoverRpcServersOptionsSchema = z.object({
  lanAddresses: lanAddressesSchema,
  topic: topicSchema.describe(
    'Shared discovery topic. Only use with trusted private-network participants.'
  ),
  timeoutMs: z
    .number()
    .int()
    .min(100)
    .max(30000)
    .optional()
    .describe(
      'Search budget in milliseconds, including TCP probes. Defaults to 5000, at most 30000.'
    )
})
export const rpcDeviceSchema = z.object({
  index: z.number().int().nonnegative().describe('Zero-based device index within this endpoint.'),
  freeMemory: z
    .number()
    .int()
    .nonnegative()
    .describe('Available device memory in bytes at discovery time.'),
  totalMemory: z.number().int().nonnegative().describe('Total device memory in bytes.')
})
export const rpcServerCandidateSchema = z.object({
  url: z.string().min(1),
  rdmaAvailable: z
    .boolean()
    .describe(
      'Server advertised RDMA availability for this endpoint at discovery time. Actual transport depends on client support and negotiation.'
    ),
  devices: z.array(rpcDeviceSchema).describe('Native served devices in endpoint enumeration order.')
})
export type RpcDevice = z.infer<typeof rpcDeviceSchema>
export const discoverRpcServersRequestSchema = discoverRpcServersOptionsSchema.extend({
  type: z.literal('discoverRpcServers'),
  requestId: requestIdSchema
})
export const discoverRpcServersResponseSchema = z.object({
  type: z.literal('discoverRpcServers'),
  servers: z.array(rpcServerCandidateSchema)
})
export type StartRpcServerOptions = z.infer<typeof startRpcServerOptionsSchema>
export type RpcServerInfo = z.infer<typeof rpcServerInfoSchema>
export type StopRpcServerOptions = z.infer<typeof stopRpcServerOptionsSchema>
export type DiscoverRpcServersOptions = z.infer<typeof discoverRpcServersOptionsSchema>
export type RpcServerCandidate = z.infer<typeof rpcServerCandidateSchema>
export type StartRpcServerRequest = z.infer<typeof startRpcServerRequestSchema>
export type StopRpcServerRequest = z.infer<typeof stopRpcServerRequestSchema>
export type DiscoverRpcServersRequest = z.infer<typeof discoverRpcServersRequestSchema>

/** Native handles remain private to the engine; callers receive an owned server ID. */
export interface RpcServerHandle {
  host: string
  port: number
  url: string
  rdmaCapable: boolean
  stop(): Promise<void>
}

/** A model-independent serving capability registered in the Bare engine. */
export interface RpcServerProvider {
  start(
    options: Omit<StartRpcServerOptions, 'discoveryTopic' | 'lanAddresses'>
  ): Promise<RpcServerHandle>
}

export const rpcServerStatusStreamOptionsSchema = z.object({
  serverId: z
    .string()
    .min(1)
    .optional()
    .describe('Observe one owned server, or all servers when omitted.')
})
export const rpcServerStatusSchema = z.object({
  serverId: z.string().min(1),
  url: z.string().min(1),
  nativeState: z.enum(['owned', 'stopped']),
  advertisement: z.enum(['inactive', 'starting', 'advertising', 'suspended', 'failed']),
  reason: z.string(),
  recovery: z.enum(['none', 'resume', 'restart']),
  error: errorResponseSchema
    .optional()
    .describe('Structured advertisement failure, including the original cause.')
})
export const rpcServerStatusStreamRequestSchema = rpcServerStatusStreamOptionsSchema.extend({
  type: z.literal('rpcServerStatusStream')
})
export const rpcServerStatusStreamResponseSchema = rpcServerStatusSchema.extend({
  type: z.literal('rpcServerStatusStream')
})
export type RpcServerStatus = z.infer<typeof rpcServerStatusSchema>
export type RpcServerStatusStreamOptions = z.infer<typeof rpcServerStatusStreamOptionsSchema>
export type RpcServerStatusStreamRequest = z.infer<typeof rpcServerStatusStreamRequestSchema>
export type RpcServerStatusStreamResponse = z.infer<typeof rpcServerStatusStreamResponseSchema>
export type RpcServerStatusEvent = Omit<RpcServerStatus, 'error'> & { error?: Error }
