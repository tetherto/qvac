import { z } from 'zod'

export const imageEmbeddingConfigSchema = z.object({
  backend: z
    .string()
    .min(1)
    .optional()
    .describe(
      'Exact GGML device name, such as CPU, CUDA0, Vulkan0 or MTL0. Omit to select GPU, then CPU. Metal and Metal0 are accepted aliases. An unavailable explicit device fails to load.'
    ),
  threads: z
    .number()
    .int()
    .min(1)
    .max(1024)
    .optional()
    .describe('CPU thread count, from 1 to 1024. Omit to use the native default.'),
  backendsDir: z
    .string()
    .min(1)
    .optional()
    .describe('Directory of GGML backend modules. Omit to use the modules shipped with Fabric.')
})

const imageFields = {
  modelId: z.string().min(1).describe('Identifier of a loaded MegaLoc model.'),
  width: z
    .number()
    .int()
    .positive()
    .max(16384)
    .optional()
    .describe(
      'Packed RGB width in pixels. Supply with height and channels, or omit all three for JPEG/PNG.'
    ),
  height: z
    .number()
    .int()
    .positive()
    .max(16384)
    .optional()
    .describe('Packed RGB height in pixels, from 1 to 16384.'),
  channels: z.literal(3).optional().describe('Packed RGB channel count. Must be 3.')
}

function validateDimensions(
  input: { width?: number | undefined; height?: number | undefined; channels?: 3 | undefined },
  ctx: z.RefinementCtx
) {
  const present = [input.width, input.height, input.channels].filter(
    (value) => value !== undefined
  ).length
  if (present !== 0 && present !== 3) {
    ctx.addIssue({
      code: 'custom',
      path: ['width'],
      message: 'Raw RGB image requires width, height and channels together'
    })
  }
}

export const embedImageParamsSchema = z
  .object({
    ...imageFields,
    image: z.base64().min(1).describe('JPEG/PNG bytes, or packed RGB bytes, encoded as base64.')
  })
  .superRefine(validateDimensions)

export const embedImageClientParamsSchema = z
  .object({
    ...imageFields,
    image: z.instanceof(Uint8Array).refine((value) => value.byteLength > 0, 'Image cannot be empty')
  })
  .superRefine(validateDimensions)
  .superRefine((input, ctx) => {
    if (
      input.width !== undefined &&
      input.height !== undefined &&
      input.channels !== undefined &&
      input.image.byteLength !== input.width * input.height * input.channels
    ) {
      ctx.addIssue({
        code: 'custom',
        path: ['image'],
        message: 'Raw RGB image byte length must equal width * height * channels'
      })
    }
  })

export const embedImageRequestSchema = embedImageParamsSchema.safeExtend({
  type: z.literal('embedImage'),
  requestId: z
    .string()
    .min(1)
    .optional()
    .describe('Request identifier for cancellation. Generated by the client when omitted.')
})

export const imageEmbeddingStatsSchema = z.object({
  totalTime: z.number().optional().describe('Native embedding time in milliseconds.'),
  backendId: z
    .number()
    .int()
    .optional()
    .describe('Native backend ID: CPU=0, Metal=1, CUDA=2, Vulkan=3, OpenCL=4, other=99.'),
  cpuFallbackNodes: z
    .number()
    .int()
    .nonnegative()
    .optional()
    .describe('Number of graph nodes scheduled on CPU fallback.'),
  weightBytes: z.number().nonnegative().optional().describe('Allocated model weight bytes.')
})

export const imageEmbeddingSchema = z
  .array(z.number())
  .length(8448)
  .describe(
    'MegaLoc descriptor with 8448 L2-normalized values. Compare descriptors with a dot product for cosine similarity.'
  )

export const embedImageResponseSchema = z.object({
  type: z.literal('embedImage'),
  embedding: imageEmbeddingSchema,
  stats: imageEmbeddingStatsSchema.optional()
})

export type ImageEmbeddingConfig = z.infer<typeof imageEmbeddingConfigSchema>
export type EmbedImageParams = z.infer<typeof embedImageParamsSchema>
export type EmbedImageClientParams = z.infer<typeof embedImageClientParamsSchema>
export type EmbedImageRequest = z.infer<typeof embedImageRequestSchema>
export type ImageEmbeddingStats = z.infer<typeof imageEmbeddingStatsSchema>
export type EmbedImageResponse = z.infer<typeof embedImageResponseSchema>
export type EmbedImageResult = Omit<EmbedImageResponse, 'type'>
