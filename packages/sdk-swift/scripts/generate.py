#!/usr/bin/env python3
"""Generate the Swift client into Sources/QvacSDK/Generated from the contract
this checkout's SDK exports. Never committed: run it before building the
package.

Usage:
  python3 scripts/generate.py
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
from swift_types import TypeGraph, literal, render_methods


PACKAGE_ROOT = Path(__file__).resolve().parent.parent
CONTRACT_ROOT = PACKAGE_ROOT.parent / "sdk" / "contract"
OUTPUT_ROOT = PACKAGE_ROOT / "Sources/QvacSDK/Generated"
TYPE_NAMES = PACKAGE_ROOT / "scripts/schema-type-names.json"
HEADER = "// Generated by scripts/generate.py. Do not edit."


def read_json(name: str):
    return json.loads((CONTRACT_ROOT / name).read_text(encoding="utf-8"))


def identifier(value: str) -> str:
    result = re.sub(r"[^A-Za-z0-9_]", "_", value)
    if not result:
        return "value"
    return f"v_{result}" if result[0].isdigit() else result


def error_case(group: str, key: str) -> str:
    words = [group.lower()] + [part.lower() for part in key.split("_") if part]
    return words[0] + "".join(word[:1].upper() + word[1:] for word in words[1:])


def render_models_registry(catalog: dict) -> str:
    fields = [
        ("name", "String"),
        ("src", "String"),
        ("registryPath", "String"),
        ("registrySource", "String"),
        ("blobCoreKey", "String"),
        ("blobBlockOffset", "Int"),
        ("blobBlockLength", "Int"),
        ("blobByteOffset", "Int"),
        ("modelId", "String"),
        ("expectedSize", "Int"),
        ("sha256Checksum", "String"),
        ("addon", "String"),
        ("engine", "String"),
        ("quantization", "String"),
        ("params", "String"),
    ]
    lines = [HEADER, "", "public struct ModelConstant: Sendable, Hashable {"]
    lines += [f"    public let {field}: {type_name}" for field, type_name in fields]
    lines += ["}", "", "public enum Models {"]
    for constant_name in sorted(catalog):
        entry = catalog[constant_name]
        lines.append(f"    public static let {identifier(constant_name)} = ModelConstant(")
        values = [f"{field}: {literal(entry[field]) if isinstance(entry[field], str) else entry[field]}"
                  for field, _ in fields]
        lines += [f"        {value}," for value in values[:-1]] + [f"        {values[-1]}", "    )"]
    lines += ["", "    public static let all: [ModelConstant] = ["]
    lines += [f"        {identifier(constant_name)}," for constant_name in sorted(catalog)]
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def render_maps(maps: dict) -> str:
    lines = [HEADER, "", "public enum ModelTypeMaps {"]
    for key in ("aliasToCanonical", "engineToAddon", "legacyEngineToCanonical"):
        lines.append(f"    public static let {key}: [String: String] = [")
        lines += [f"        {literal(alias)}: {literal(value)}," for alias, value in sorted(maps[key].items())]
        lines += ["    ]", ""]
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def render_errors(codes: dict) -> str:
    entries = [(group, key, value) for group in ("server", "client", "registry")
               for key, value in sorted(codes[group].items())]
    lines = [HEADER, "", "public enum QvacErrorKind: Sendable, Hashable, CaseIterable {"]
    lines += [f"    case `{error_case(group, key)}`" for group, key, _ in entries]
    lines += ["", "    public var name: String {", "        switch self {"]
    lines += [f"        case .`{error_case(group, key)}`: {literal(key)}" for group, key, _ in entries]
    lines += ["        }", "    }", "", "    public var code: Int {", "        switch self {"]
    lines += [f"        case .`{error_case(group, key)}`: {value}" for group, key, value in entries]
    lines += ["        }", "    }", "", "    static let byName: [String: [QvacErrorKind]] = ["]
    grouped: dict[str, list[str]] = {}
    for group, key, _ in entries:
        grouped.setdefault(key, []).append(f".`{error_case(group, key)}`")
    lines += [f"        {literal(key)}: [{', '.join(kinds)}]," for key, kinds in sorted(grouped.items())]
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def render_version(version: str) -> str:
    return f"{HEADER}\n\npublic enum QvacSDKVersion {{\n    public static let current = {literal(version)}\n}}\n"


def generated_files() -> dict[str, str]:
    schema = read_json("schema.json")
    manifest = read_json("manifest.json")
    graph = TypeGraph(schema, json.loads(TYPE_NAMES.read_text(encoding="utf-8")))
    version = json.loads((CONTRACT_ROOT.parent / "package.json").read_text(encoding="utf-8"))["version"]
    return {
        "SchemaTypes.swift": graph.render(HEADER),
        "SchemaMethods.swift": render_methods(graph, manifest, HEADER),
        "Models.swift": render_models_registry(read_json("models.json")),
        "ModelTypeMaps.swift": render_maps(read_json("model-type-maps.json")),
        "ErrorKinds.swift": render_errors(read_json("error-codes.json")),
        "SdkVersion.swift": render_version(version),
    }


def export_contract() -> None:
    npm = shutil.which("npm")
    if npm is None:
        raise SystemExit("npm is not on PATH; the SDK contract is exported with it")
    subprocess.run([npm, "run", "contract:export"], cwd=CONTRACT_ROOT.parent, check=True)


def main() -> int:
    export_contract()
    files = generated_files()
    shutil.rmtree(OUTPUT_ROOT, ignore_errors=True)
    OUTPUT_ROOT.mkdir(parents=True)
    for name, content in files.items():
        (OUTPUT_ROOT / name).write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
