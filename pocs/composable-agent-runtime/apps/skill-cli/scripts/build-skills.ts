import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { hashBundledSkills } from '@qvac/harness/skill-host'

// Build-time only. The directory walk lives here rather than in Harness so its
// node:fs import never reaches a Bare worker bundle.
const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const skillsDirectory = path.join(packageRoot, 'skills')
const outputFile = path.join(packageRoot, 'lib', 'skills', 'bundled-skills.ts')

function collect(directory: string, prefix = ''): Record<string, string> {
  const files: Record<string, string> = {}
  const entries = fs
    .readdirSync(directory, { withFileTypes: true })
    .sort((left, right) => left.name.localeCompare(right.name))
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name)
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isDirectory()) Object.assign(files, collect(absolute, relative))
    else files[relative] = fs.readFileSync(absolute, 'utf8')
  }
  return files
}

const files = collect(skillsDirectory)
const hash = hashBundledSkills(files)
const entries = Object.entries(files)
  .map(([relativePath, content]) => `  ${JSON.stringify(relativePath)}: ${JSON.stringify(content)}`)
  .join(',\n')

const output =
  `// This file is autogenerated by scripts/build-skills.ts from skills/.\n` +
  `// Do not edit manually. Regenerate with: bun run build:skills\n\n` +
  `export const BUNDLED_SKILLS_HASH = '${hash}'\n\n` +
  `export const BUNDLED_SKILLS: Readonly<Record<string, string>> = {\n` +
  `${entries}\n` +
  `}\n`

fs.writeFileSync(outputFile, output)
console.log(
  `wrote ${path.relative(packageRoot, outputFile)} (${Object.keys(files).length} files, hash ${hash})`
)
