import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildBundleFromDirectory } from '../lib/skills/build-bundle.ts'

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const skillsDirectory = path.join(packageRoot, 'skills')
const outputFile = path.join(packageRoot, 'lib', 'skills', 'bundled-skills.ts')

const bundle = buildBundleFromDirectory(skillsDirectory)
const entries = Object.entries(bundle.files)
  .map(([relativePath, content]) => `  ${JSON.stringify(relativePath)}: ${JSON.stringify(content)}`)
  .join(',\n')

const output =
  `// This file is autogenerated by scripts/build-skills.ts from skills/.\n` +
  `// Do not edit manually. Regenerate with: bun run build:skills\n\n` +
  `export const BUNDLED_SKILLS_HASH = '${bundle.hash}'\n\n` +
  `export const BUNDLED_SKILLS: Readonly<Record<string, string>> = {\n` +
  `${entries}\n` +
  `}\n`

fs.writeFileSync(outputFile, output)
console.log(
  `wrote ${path.relative(packageRoot, outputFile)} (${Object.keys(bundle.files).length} files, hash ${bundle.hash})`
)
