#!/usr/bin/env node
/**
 * Updates docs/website/src/lib/versions.ts from docs/website/content/docs/sdk/api directory listing.
 */
const path = require('path');
const fs = require('fs');

const versionArg = process.argv[2];
if (!versionArg) {
  console.error('Usage: node scripts/update-versions-list.cjs <version>');
  process.exit(1);
}

const repoRoot = path.resolve(__dirname, '../..');
const apiDir = path.join(repoRoot, 'docs/website/content/docs/sdk/api');
const versionsFile = path.join(repoRoot, 'docs/website/src/lib/versions.ts');

if (!fs.existsSync(apiDir)) {
  console.error('API dir not found:', apiDir);
  process.exit(1);
}

const entries = fs.readdirSync(apiDir, { withFileTypes: true });
const versions = entries
  .filter((e) => e.isDirectory() && e.name !== 'latest')
  .map((e) => e.name)
  .sort((a, b) => {
    const aVer = a.replace(/^v/, '').split('.').map(Number);
    const bVer = b.replace(/^v/, '').split('.').map(Number);
    for (let i = 0; i < 3; i++) {
      const ai = aVer[i] ?? 0;
      const bi = bVer[i] ?? 0;
      if (ai !== bi) return bi - ai;
    }
    return 0;
  });

const latest = versions[0] || 'latest';
const content = `// Auto-generated by update-versions-list.cjs
// Do not edit manually

export interface Version {
  label: string;
  path: string;
  isLatest?: boolean;
}

export const VERSIONS: Version[] = [
  { label: 'Latest (v${latest.replace(/^v/, '')})', path: 'latest', isLatest: true },
${versions.map((v) => `  { label: '${v}', path: '${v}' },`).join('\n')}
];

export const LATEST_VERSION = '${latest}';
`;

fs.mkdirSync(path.dirname(versionsFile), { recursive: true });
fs.writeFileSync(versionsFile, content, 'utf8');
console.log('Updated', versionsFile, 'with', versions.length, 'versions. Latest:', latest);
