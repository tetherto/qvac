/**
 * Bindings between hand-written pages and the API symbols they describe, and
 * the lock that records each binding's surface at the page's last review.
 *
 * A page declares `binds: [<symbol-id>, …]` in its frontmatter. The lock,
 * `api-bindings.lock.json` at the documentation root, maps each page to the
 * hash of every symbol it binds. A surface change leaves the lock stale for
 * every page bound to it, and the check names them; `docs:lock` rewrites the
 * lock, so the review shows in the pull request's diff.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import * as path from 'node:path'
import type { DocumentedSoftwareKind } from '../../src/lib/versions'
import { WHOLE_SURFACE, surfaceHash, type Surface } from './surface'

export const LOCK_FILE = 'api-bindings.lock.json'

/** Page path relative to the documentation root → the symbols it binds. */
export type PageBindings = Map<string, string[]>

/** Page path → symbol → surface hash at the page's last review. */
export type Lock = Record<string, Record<string, string>>

const GENERATED_MARKER = /\{\/\*\s*Generated by [^*]*Do not edit\.\s*\*\/\}/

/** A page the reference generator writes, which its freshness check keeps current. */
export function isGeneratedPage(source: string): boolean {
  return GENERATED_MARKER.test(source)
}

/** The `binds` list of a page's frontmatter, in flow (`[a, b]`) or block form. */
export function bindsOf(source: string): string[] {
  const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(source)?.[1]
  if (!frontmatter) return []
  const lines = frontmatter.split(/\r?\n/)
  const start = lines.findIndex((line) => /^binds\s*:/.test(line))
  if (start === -1) return []
  const inline = lines[start].replace(/^binds\s*:\s*/, '').trim()
  if (inline.startsWith('[')) {
    return inline
      .replace(/^\[|\]$/g, '')
      .split(',')
      .map(unquote)
      .filter(Boolean)
  }
  const items: string[] = []
  for (const line of lines.slice(start + 1)) {
    const item = /^\s+-\s+(.+)$/.exec(line)
    if (!item) break
    items.push(unquote(item[1]))
  }
  return items
}

function unquote(value: string): string {
  return value.trim().replace(/^(['"])(.*)\1$/, '$2')
}

/** Every page of a documentation root, relative to it, outside `_generated/`. */
export function pagesOf(docsRoot: string): string[] {
  const pages: string[] = []
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) walk(full)
      else if (entry.name.endsWith('.mdx')) pages.push(path.relative(docsRoot, full).split(path.sep).join('/'))
    }
  }
  if (existsSync(docsRoot)) walk(docsRoot)
  return pages.sort()
}

export interface PageScan {
  bindings: PageBindings
  /** Generated pages that declare bindings anyway. */
  generatedWithBinds: string[]
}

export function scanPages(docsRoot: string): PageScan {
  const bindings: PageBindings = new Map()
  const generatedWithBinds: string[] = []
  for (const page of pagesOf(docsRoot)) {
    const source = readFileSync(path.join(docsRoot, page), 'utf-8')
    const binds = bindsOf(source)
    if (binds.length === 0) continue
    if (isGeneratedPage(source)) generatedWithBinds.push(page)
    else bindings.set(page, binds)
  }
  return { bindings, generatedWithBinds }
}

export function readLock(docsRoot: string): Lock {
  const file = path.join(docsRoot, LOCK_FILE)
  if (!existsSync(file)) return {}
  return (JSON.parse(readFileSync(file, 'utf-8')) as { pages?: Lock }).pages ?? {}
}

/** The lock that records every current binding as reviewed. */
export function lockFor(bindings: PageBindings, surface: Surface): Lock {
  const lock: Lock = {}
  for (const page of [...bindings.keys()].sort()) {
    const entries = [...new Set(bindings.get(page)!)]
      .sort()
      .map((id) => [id, surfaceHash(surface, id)] as const)
      .filter((entry): entry is readonly [string, string] => entry[1] !== null)
    if (entries.length > 0) lock[page] = Object.fromEntries(entries)
  }
  return lock
}

export function writeLock(docsRoot: string, lock: Lock): void {
  const body = {
    '//': 'Written by `npm run docs:lock` in docs/website. Each entry is the surface hash of a symbol a page binds, at the page\'s last review.',
    pages: lock,
  }
  writeFileSync(path.join(docsRoot, LOCK_FILE), `${JSON.stringify(body, null, 2)}\n`)
}

export interface BindingProblem {
  kind: 'unknown-symbol' | 'kind-rigor' | 'generated-binds' | 'drift' | 'unreviewed' | 'stale-lock' | 'uncovered'
  page?: string
  symbol: string
  message: string
}

export interface CheckInput {
  kind: DocumentedSoftwareKind
  surface: Surface
  scan: PageScan
  lock: Lock
}

/** Everything wrong with a software's bindings, its lock, and its coverage. */
export function checkBindings({ kind, surface, scan, lock }: CheckInput): BindingProblem[] {
  const problems: BindingProblem[] = []

  for (const page of scan.generatedWithBinds) {
    problems.push({
      kind: 'generated-binds',
      page,
      symbol: '',
      message: `${page} is generated and must not declare bindings: its freshness check keeps it current.`,
    })
  }

  for (const [page, binds] of scan.bindings) {
    for (const id of binds) {
      if (kind === 'platform' && id !== WHOLE_SURFACE) {
        problems.push({ kind: 'kind-rigor', page, symbol: id, message: `${page} binds ${id}, but a platform binds its whole surface: use \`${WHOLE_SURFACE}\`.` })
        continue
      }
      if (kind === 'product' && id === WHOLE_SURFACE) {
        problems.push({ kind: 'kind-rigor', page, symbol: id, message: `${page} binds \`${WHOLE_SURFACE}\`, but a product binds each symbol it describes.` })
        continue
      }
      const current = surfaceHash(surface, id)
      if (current === null) {
        problems.push({ kind: 'unknown-symbol', page, symbol: id, message: `${page} binds ${id}, which is not in the public surface.` })
        continue
      }
      const recorded = lock[page]?.[id]
      if (recorded === undefined) {
        problems.push({ kind: 'unreviewed', page, symbol: id, message: `${page} binds ${id}, but the lock records no review of it.` })
      } else if (recorded !== current) {
        problems.push({ kind: 'drift', page, symbol: id, message: `${id} changed since ${page} was last reviewed.` })
      }
    }
  }

  for (const [page, entries] of Object.entries(lock)) {
    const binds = new Set(scan.bindings.get(page) ?? [])
    for (const id of Object.keys(entries)) {
      if (!binds.has(id)) {
        problems.push({ kind: 'stale-lock', page, symbol: id, message: `The lock records ${id} for ${page}, which no longer binds it.` })
      }
    }
  }

  if (kind === 'product') {
    const bound = new Set([...scan.bindings.values()].flat())
    for (const id of [...surface.keys()].sort()) {
      if (!bound.has(id)) problems.push({ kind: 'uncovered', symbol: id, message: `${id} is public, and no page binds it.` })
    }
  }

  return problems
}
