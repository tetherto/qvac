#!/usr/bin/env bun
/**
 * Generate the SDK's API surface data, committed with its documentation.
 *
 * Usage:
 *   bun run scripts/api-reference/generate-sdk-data.ts           # write
 *   bun run scripts/api-reference/generate-sdk-data.ts --check   # fail when stale
 *
 * Writes into `packages/sdk/docs/users/_generated/`:
 *
 *   - `js-api.json` — every public JavaScript function: its signature, its
 *     summary, and its client-side return fields, extracted by TypeDoc from
 *     `packages/sdk` (`scripts/api-docs/extract.ts`).
 *   - `python-api.json` — every public Python function: its signature and
 *     parameters, read from `packages/sdk-python` source by
 *     `python-surface.py`, which needs no third-party package.
 *
 * It also writes the reference pages, `packages/sdk/docs/users/reference/api/`:
 * one page per public function, rendered by `<FunctionReference>`, and an
 * index. They are stubs: every fact on them is read from the data at build.
 *
 * Field facts — types, nesting, constraints, descriptions — come from the
 * SDK's exported contract (`packages/sdk/contract/`), not from here. These
 * files add what the contract cannot know: the client functions themselves.
 *
 * Both need the packages' sources, so they are generated here, in the
 * repository, and committed. The site build only reads them, which is what
 * lets a line pinned to an older commit build from committed files alone.
 */
import { spawnSync } from 'node:child_process'
import * as fs from 'node:fs/promises'
import * as path from 'node:path'
import { extractApiData } from '../api-docs/extract'

const WEBSITE_ROOT = path.resolve(import.meta.dirname, '..', '..')
const MONOREPO_ROOT = path.resolve(WEBSITE_ROOT, '..', '..')
const SDK_PATH = path.join(MONOREPO_ROOT, 'packages', 'sdk')
const PYTHON_PACKAGE = path.join(MONOREPO_ROOT, 'packages', 'sdk-python', 'src', 'tetherto', 'qvac_sdk')
export const GENERATED_DIR = path.join(SDK_PATH, 'docs', 'users', '_generated')
export const REFERENCE_DIR = path.join(SDK_PATH, 'docs', 'users', 'reference', 'api')

interface JsSummary {
  name: string
  description: string
  deprecated: string | null
}

function firstSentence(text: string): string {
  const flat = text.replace(/\s+/g, ' ').trim()
  const match = /^(.+?[.!?])(\s|$)/.exec(flat)
  return (match ? match[1] : flat).replace(/"/g, '\\"')
}

/** The reference pages: one stub per public function, plus the index. */
function referencePages(functions: JsSummary[]): Record<string, string> {
  const pages: Record<string, string> = {
    'index.mdx': [
      '---',
      'title: API reference',
      'sidebarTitle: API',
      'icon: BookA',
      'description: Every public function of @qvac/sdk, one page each',
      '---',
      '',
      '{/* Generated by docs/website/scripts/api-reference/generate-sdk-data.ts. Do not edit. */}',
      '',
      '<FunctionIndex />',
      '',
    ].join('\n'),
    'meta.json': JSON.stringify({ title: 'API', pages: ['index', ...functions.map((fn) => fn.name)] }, null, 2) + '\n',
  }
  for (const fn of functions) {
    pages[`${fn.name}.mdx`] = [
      '---',
      `title: ${fn.name}`,
      'titleStyle: code',
      `description: "${firstSentence(fn.description || fn.name)}"`,
      '---',
      '',
      '{/* Generated by docs/website/scripts/api-reference/generate-sdk-data.ts. Do not edit. */}',
      '',
      `<FunctionReference fn="${fn.name}" />`,
      '',
    ].join('\n')
  }
  return pages
}

async function javascriptSurface(): Promise<string> {
  const pkg = JSON.parse(await fs.readFile(path.join(SDK_PATH, 'package.json'), 'utf-8')) as { version: string }
  const [major, minor] = pkg.version.split('.')
  const data = await extractApiData(SDK_PATH, `v${major}.${minor}`, { forceExtract: true })
  const functions = data.functions.map((fn) => ({
    name: fn.name,
    signature: fn.signature,
    description: fn.description,
    returns: fn.returns?.type ?? null,
    returnFields: (fn.returnFields ?? []).map((field) => ({
      name: field.name,
      type: field.type,
      required: field.required,
    })),
    throws: fn.throws ?? [],
    deprecated: fn.deprecated ?? null,
  }))
  return JSON.stringify({ functions }, null, 2) + '\n'
}

function pythonSurface(): string {
  const run = spawnSync('python3', ['-I', path.join(import.meta.dirname, 'python-surface.py'), PYTHON_PACKAGE], {
    encoding: 'utf-8',
  })
  if (run.status !== 0) throw new Error(`python-surface.py failed:\n${run.stderr}`)
  return JSON.stringify(JSON.parse(run.stdout), null, 2) + '\n'
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check')
  const js = await javascriptSurface()
  const outputs: Record<string, string> = {
    [path.join(GENERATED_DIR, 'js-api.json')]: js,
    [path.join(GENERATED_DIR, 'python-api.json')]: pythonSurface(),
  }
  const pages = referencePages((JSON.parse(js) as { functions: JsSummary[] }).functions)
  for (const [file, content] of Object.entries(pages)) outputs[path.join(REFERENCE_DIR, file)] = content

  const expected = new Set(Object.keys(outputs))
  const leftovers = (await fs.readdir(REFERENCE_DIR).catch(() => [] as string[]))
    .map((file) => path.join(REFERENCE_DIR, file))
    .filter((file) => !expected.has(file))

  const stale: string[] = []
  for (const [target, content] of Object.entries(outputs)) {
    if (check) {
      const current = await fs.readFile(target, 'utf-8').catch(() => null)
      if (current !== content) stale.push(path.relative(MONOREPO_ROOT, target))
    } else {
      await fs.mkdir(path.dirname(target), { recursive: true })
      await fs.writeFile(target, content)
    }
  }
  for (const leftover of leftovers) {
    if (check) stale.push(`${path.relative(MONOREPO_ROOT, leftover)} (no longer a public function)`)
    else await fs.rm(leftover)
  }
  if (stale.length > 0) {
    console.error(`stale generated API data — run \`npm run docs:sdk-api\`:\n  ${stale.join('\n  ')}`)
    process.exit(1)
  }
  if (!check) console.log(`wrote ${Object.keys(outputs).length} file(s), removed ${leftovers.length}`)
}

if (import.meta.main) {
  main().catch((error: Error) => {
    console.error(error.message)
    process.exit(1)
  })
}
