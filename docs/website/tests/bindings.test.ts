import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import * as path from 'node:path'
import { describe, expect, it } from 'vitest'
import { bindsOf, checkBindings, isGeneratedPage, lockFor, readLock, scanPages, writeLock, type BindingProblem } from '../scripts/bindings/bindings'
import { canonical, projectSurface, surfaceHash, type Surface } from '../scripts/bindings/surface'

const MONOREPO = path.resolve(import.meta.dirname, '..', '..', '..')

function page(binds: string[], body = 'Prose.'): string {
  return `---\ntitle: Page\nbinds:\n${binds.map((id) => `  - "${id}"`).join('\n')}\n---\n\n${body}\n`
}

function docsRoot(pages: Record<string, string>): string {
  const root = mkdtempSync(path.join(tmpdir(), 'bindings-'))
  for (const [file, source] of Object.entries(pages)) {
    mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
    writeFileSync(path.join(root, file), source)
  }
  return root
}

function kinds(problems: BindingProblem[]): string[] {
  return problems.map((problem) => `${problem.kind} ${problem.page ?? '-'} ${problem.symbol}`)
}

const surface = (request: Record<string, unknown>): Surface =>
  new Map<string, unknown>([
    ['fn:translate', { js: 'translate(params)', request }],
    ['fn:embed', { js: 'embed(params)', request: {} }],
  ])

describe('frontmatter bindings', () => {
  it('reads the block form, quoted or not', () => {
    expect(bindsOf('---\ntitle: T\nbinds:\n  - fn:translate\n  - "endpoint:GET /v1/files/{id}"\nicon: X\n---\n')).toEqual([
      'fn:translate',
      'endpoint:GET /v1/files/{id}',
    ])
  })

  it('reads the flow form', () => {
    expect(bindsOf('---\nbinds: [fn:translate, "fn:embed"]\n---\n')).toEqual(['fn:translate', 'fn:embed'])
  })

  it('is empty without frontmatter or without binds', () => {
    expect(bindsOf('# Title\n')).toEqual([])
    expect(bindsOf('---\ntitle: T\n---\n')).toEqual([])
  })

  it('recognizes a generated page by its marker', () => {
    expect(isGeneratedPage('{/* Generated by docs/website/scripts/x.ts. Do not edit. */}')).toBe(true)
    expect(isGeneratedPage('Hand-written.')).toBe(false)
  })
})

describe('the projected-surface hash', () => {
  it('ignores key order and whitespace', () => {
    expect(canonical({ b: 'one  two', a: [1, { y: 2, x: 1 }] })).toBe(canonical({ a: [1, { x: 1, y: 2 }], b: 'one two' }))
  })

  it('changes when a field is added', () => {
    expect(surfaceHash(surface({ text: 1 }), 'fn:translate')).not.toBe(surfaceHash(surface({ text: 1, to: 2 }), 'fn:translate'))
  })

  it('hashes the whole surface for `surface`, and nothing for an unknown symbol', () => {
    expect(surfaceHash(surface({}), 'surface')).toMatch(/^[0-9a-f]{16}$/)
    expect(surfaceHash(surface({}), 'fn:missing')).toBeNull()
  })
})

describe('the binding check', () => {
  const pages = { 'translation.mdx': page(['fn:translate']), 'embeddings.mdx': page(['fn:embed']) }

  it('passes once the lock records every binding', () => {
    const root = docsRoot(pages)
    const scan = scanPages(root)
    writeLock(root, lockFor(scan.bindings, surface({ text: 1 })))
    expect(checkBindings({ kind: 'product', surface: surface({ text: 1 }), scan, lock: readLock(root) })).toEqual([])
  })

  it('fails on a changed surface with the lock unchanged, naming the page', () => {
    const root = docsRoot(pages)
    const scan = scanPages(root)
    const lock = lockFor(scan.bindings, surface({ text: 1 }))
    expect(kinds(checkBindings({ kind: 'product', surface: surface({ text: 1, to: 2 }), scan, lock }))).toEqual([
      'drift translation.mdx fn:translate',
    ])
  })

  it('passes an implementation change that leaves the surface alone', () => {
    const root = docsRoot(pages)
    const scan = scanPages(root)
    const lock = lockFor(scan.bindings, surface({ text: 1 }))
    expect(checkBindings({ kind: 'product', surface: new Map(surface({ text: 1 })), scan, lock })).toEqual([])
  })

  it('names unreviewed bindings, stale lock entries, and unknown symbols', () => {
    const root = docsRoot({ ...pages, 'extra.mdx': page(['fn:gone']) })
    const scan = scanPages(root)
    const lock = { 'translation.mdx': { 'fn:embed': 'x' } }
    expect(kinds(checkBindings({ kind: 'product', surface: surface({}), scan, lock }))).toEqual([
      'unreviewed embeddings.mdx fn:embed',
      'unknown-symbol extra.mdx fn:gone',
      'unreviewed translation.mdx fn:translate',
      'stale-lock translation.mdx fn:embed',
    ])
  })

  it('fails coverage for a product symbol no page binds', () => {
    const root = docsRoot({ 'translation.mdx': page(['fn:translate']) })
    const scan = scanPages(root)
    const lock = lockFor(scan.bindings, surface({}))
    expect(kinds(checkBindings({ kind: 'product', surface: surface({}), scan, lock }))).toEqual(['uncovered - fn:embed'])
  })

  it('binds a platform as a whole, with no coverage check', () => {
    const root = docsRoot({ 'usage.mdx': page(['surface']), 'other.mdx': page(['fn:embed']) })
    const scan = scanPages(root)
    const lock = lockFor(scan.bindings, surface({}))
    expect(kinds(checkBindings({ kind: 'platform', surface: surface({}), scan, lock }))).toEqual(['kind-rigor other.mdx fn:embed'])
    const changed = checkBindings({ kind: 'platform', surface: surface({ text: 1 }), scan, lock })
    expect(kinds(changed)).toContain('drift usage.mdx surface')
  })

  it('refuses bindings on a generated page', () => {
    const root = docsRoot({ 'reference/translate.mdx': page(['fn:translate'], '{/* Generated by x.ts. Do not edit. */}') })
    const scan = scanPages(root)
    expect(kinds(checkBindings({ kind: 'platform', surface: surface({}), scan, lock: {} }))).toEqual([
      'generated-binds reference/translate.mdx ',
    ])
  })
})

describe('the bindings of the working tree', () => {
  it('give the SDK a function symbol per public function, with its expanded request', () => {
    const projected = projectSurface({ root: MONOREPO, paths: ['packages/sdk/docs/users', 'packages/sdk/contract'] })
    const translate = projected.get('fn:translate') as { request: unknown }
    expect(translate).toBeDefined()
    expect(JSON.stringify(translate.request)).not.toContain('"$ref":"#/$defs/')
  })

  it('give the CLI its commands and its HTTP endpoints', () => {
    const projected = projectSurface({ root: MONOREPO, paths: ['packages/cli/docs/users'] })
    expect(projected.has('command:qvac serve')).toBe(true)
    expect(projected.has('endpoint:POST /v1/chat/completions')).toBe(true)
  })

  it('keep the SDK lock current', () => {
    const paths = ['packages/sdk/docs/users', 'packages/sdk/contract']
    const root = path.join(MONOREPO, paths[0])
    const scan = scanPages(root)
    const recorded = JSON.parse(readFileSync(path.join(root, 'api-bindings.lock.json'), 'utf-8')).pages
    expect(recorded).toEqual(lockFor(scan.bindings, projectSurface({ root: MONOREPO, paths })))
  })
})
